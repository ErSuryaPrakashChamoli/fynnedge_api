/**
 * Writes the expected engine output for every parity case.
 *
 * Laravel is the authority, so the fixture is generated from it and both test
 * suites assert against the result. If either engine changes behaviour, one of
 * the two suites fails.
 */
class GenerateParityFixture extends Command
{
    protected $signature = 'fynn:parity-fixture {--check : Fail instead of writing when the fixture is stale}';

    protected $description = 'Generate the Laravel/Flutter parity fixtures';

    public function handle(
        FinancialEngine $engine,
        FynnScoreEngine $scoring,
        FynnMatchEngine $matching,
    ): int {
        if ($this->writeFinancialFixture($engine) === self::FAILURE) {
            return self::FAILURE;
        }

        if ($this->writeScoreFixture($engine, $scoring) === self::FAILURE) {
            return self::FAILURE;
        }

        if ($this->writeMatchFixture($engine, $matching) === self::FAILURE) {
            return self::FAILURE;
        }

        if ($this->writeApplicationFixture() === self::FAILURE) {
            return self::FAILURE;
        }

        if ($this->writeConsentFixture() === self::FAILURE) {
            return self::FAILURE;
        }

        if ($this->writeTwinFixture() === self::FAILURE) {
            return self::FAILURE;
        }

        return $this->writeAttentionFixture($engine);
    }

    /**
     * Every attention case, so the Flutter rules raise the same items, in the
     * same order, with the same words.
     */
    private function writeAttentionFixture(FinancialEngine $engine): int
    {
        $rules = app(AttentionRules::class);
        $cases = [];

        foreach (AttentionCases::all() as $case) {
            $p = $case['profile'];

            $goals = collect($case['goals'])->map(
                fn (array $g) => new FinancialGoal([
                    'title' => $g['title'],
                    'category' => 'other',
                    'target_amount' => $g['target_amount'],
                    'saved_amount' => $g['saved_amount'],
                    'target_date' => $g['target_date'],
                    'status' => 'active',
                ])
            );

            $snapshot = $engine->calculate(
                income: Money::of($p['monthly_income']),
                expenses: Money::of($p['monthly_expenses']),
                existingEmi: Money::of($p['existing_emi']),
                otherObligations: Money::of($p['other_obligations']),
                savings: Money::of($p['savings']),
            );

            $cases[] = [
                'name' => $case['name'],
                'note' => $case['note'],
                'input' => [
                    'profile' => $p,
                    'goals' => $case['goals'],
                ],
                'expected' => array_map(
                    fn (AttentionItem $item) => $item->toArray(),
                    // No applications: the only application rule needs a
                    // provider status no provider can send yet.
                    $rules->evaluate($snapshot, $goals, collect()),
                ),
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter attention rules are '
                .'asserted against this file. Do not edit by hand.',
            'affordability_reference_percent' => FinancialEngine::AFFORDABILITY_CEILING_PERCENT,
            'emergency_fund_target_months' => FinancialEngine::EMERGENCY_FUND_TARGET_MONTHS,
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('home_attention_parity.json', $json);
    }

    /**
     * Every FynnTwin case, so the Flutter engine is held to the same
     * projections as the Laravel one.
     */
    private function writeTwinFixture(): int
    {
        $engine = app(FynnTwinEngine::class);
        $financial = app(FinancialEngine::class);
        $products = app(ProductRepository::class);

        $cases = [];

        foreach (TwinCases::all() as $case) {
            $scenario = $case['scenario'];
            $type = ScenarioType::from($scenario['type']);

            $product = isset($scenario['product_id'])
                ? $products->find($scenario['product_id'])
                : null;

            $current = $financial->calculate(
                income: Money::of($case['profile']['monthly_income']),
                expenses: Money::of($case['profile']['monthly_expenses']),
                existingEmi: Money::of($case['profile']['existing_emi']),
                otherObligations: Money::of($case['profile']['other_obligations']),
                savings: Money::of($case['profile']['savings']),
            );

            $projection = $engine->simulate(
                $current,
                new TwinScenario(
                    type: $type,
                    amount: isset($scenario['amount'])
                        ? Money::of($scenario['amount'])
                        : null,
                    tenureMonths: $scenario['tenure_months'] ?? null,
                    productId: $scenario['product_id'] ?? null,
                    monthlyChange: isset($scenario['monthly_change'])
                        ? Money::of($scenario['monthly_change'])
                        : null,
                    monthlyAmount: isset($scenario['monthly_amount'])
                        ? Money::of($scenario['monthly_amount'])
                        : null,
                    months: $scenario['months'] ?? null,
                ),
                $product,
            );

            $cases[] = [
                'name' => $case['name'],
                'note' => $case['note'],
                'input' => [
                    'profile' => $case['profile'],
                    'scenario' => $scenario,
                ],
                'expected' => $projection->toArray(),
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter Twin engine is '
                .'asserted against this file. Do not edit by hand.',
            'affordability_reference_percent' => FinancialEngine::AFFORDABILITY_CEILING_PERCENT,
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('fynntwin_parity.json', $json);
    }

    /**
     * The consent catalogue, so mock mode cannot offer something the API
     * refuses — or, worse, offer something the API does not have at all.
     */
    private function writeConsentFixture(): int
    {
        $types = [];

        foreach (ConsentType::cases() as $type) {
            $types[] = [
                'type' => $type->value,
                'label' => $type->label(),
                'description' => $type->description(),
                'is_required' => $type->isRequired(),
                'is_available' => $type->isAvailable(),
                'unavailable_reason' => $type->unavailableReason(),
                'current_version' => $type->currentVersion(),
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter consent catalogue is '
                .'asserted against this file. Do not edit by hand.',
            '_legal_note' => 'These descriptions are FynnEdge\'s own '
                .'plain-English account of what the software does. No privacy '
                .'policy or terms document exists in this project yet. When '
                .'that copy is written it becomes a new version and every '
                .'customer is asked again.',
            'types' => $types,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('consent_catalogue.json', $json);
    }

    /**
     * One payload per lifecycle state the implementation can actually reach.
     *
     * The provider-decision states are deliberately absent: nothing in this
     * codebase can produce one, and a fixture for a state the product cannot
     * enter would be a promise the code does not keep.
     */
    private function writeApplicationFixture(): int
    {
        $cases = [];

        // Rolled back: generating a fixture must not leave rows behind.
        DB::beginTransaction();

        try {
            $user = User::factory()->create();
            $user->ensureProfiles();
            $user->financialProfile->update([
                'monthly_income' => 100000,
                'monthly_expenses' => 40000,
                'existing_emi' => 20000,
                'savings' => 180000,
            ]);
            $user->customerProfile->update(['age' => 34]);

            $service = app(LoanApplicationService::class);
            $input = [
                'product_id' => 'prod_bl_b',
                'amount' => '1000000.00',
                'tenure_months' => 60,
            ];

            $started = $service->create($user, $input, 'fixture-started');
            $cases[] = [
                'name' => 'started',
                'note' => 'Created from a match. Nothing sent, nothing acknowledged.',
                'payload' => $this->applicationArray($started),
            ];

            $submitted = $service->submit(
                $service->create($user, $input, 'fixture-submitted')
            );
            $cases[] = [
                'name' => 'submitted',
                'note' => 'Handed to the mock gateway, which acknowledged it '
                    .'and sent it nowhere.',
                'payload' => $this->applicationArray($submitted),
            ];

            $cancelled = $service->cancel(
                $service->create($user, $input, 'fixture-cancelled')
            );
            $cases[] = [
                'name' => 'cancelled',
                'note' => 'Withdrawn by the customer.',
                'payload' => $this->applicationArray($cancelled),
            ];
        } finally {
            DB::rollBack();
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter application model is '
                .'asserted against this file. Do not edit by hand.',
            'implemented_states' => ['started', 'submitted', 'cancelled'],
            'provider_states' => [
                'under_review', 'action_needed', 'approved', 'declined', 'disbursed',
            ],
            'provider_states_note' => 'Defined by the model and set only by a '
                .'gateway relaying a real provider response. No gateway in '
                .'this codebase produces one, so there is no fixture for them.',
            'acknowledgements' => LoanApplicationService::acknowledgements(),
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('application_lifecycle.json', $json);
    }

    /**
     * The resource payload, with the fields that move on every run removed.
     *
     * Ids, references and timestamps differ per generation; keeping them
     * would make the fixture stale the moment it was written.
     *
     * @return array<string, mixed>
     */
    private function applicationArray(LoanApplication $application): array
    {
        $array = (new LoanApplicationResource($application->load('events')))
            ->toArray(request());

        foreach (['id', 'created_at', 'updated_at', 'submitted_at', 'cancelled_at', 'acknowledged_at', 'reference'] as $volatile) {
            if (array_key_exists($volatile, $array)) {
                $array[$volatile] = $array[$volatile] === null ? null : '<varies>';
            }
        }

        $array['events'] = array_map(function (array $event) {
            $event['at'] = '<varies>';

            return $event;
        }, $array['events']);

        return $array;
    }

    private function writeFinancialFixture(FinancialEngine $engine): int
    {
        $asOf = Carbon::parse(ParityCases::AS_OF);
        $cases = [];

        foreach (ParityCases::all() as $case) {
            $profile = new FinancialProfile($case['profile']);

            $goals = collect($case['goals'])->map(function (array $g) use ($asOf) {
                $goal = new FinancialGoal([
                    'title' => $g['title'],
                    'target_amount' => $g['target_amount'],
                    'saved_amount' => $g['saved_amount'],
                    'target_date' => $asOf->copy()->addDays($g['days_from_as_of']),
                ]);
                $goal->id = $g['id'];

                return $goal;
            });

            $cases[] = [
                'name' => $case['name'],
                'input' => [
                    'profile' => $case['profile'],
                    'goals' => $case['goals'],
                ],
                'expected' => $engine->snapshot($profile, $goals, $asOf)->toArray(),
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter engine is asserted '
                .'against this file. Do not edit by hand.',
            'as_of' => ParityCases::AS_OF,
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('financial_parity.json', $json);
    }

    private function writeScoreFixture(
        FinancialEngine $engine,
        FynnScoreEngine $scoring,
    ): int {
        $asOf = Carbon::parse(ParityCases::AS_OF);
        $cases = [];

        foreach (ScoreCases::all() as $case) {
            $profile = new FinancialProfile($case['profile']);

            $goals = collect($case['goals'])->map(function (array $g) use ($asOf) {
                $goal = new FinancialGoal([
                    'title' => $g['title'],
                    'target_amount' => $g['target_amount'],
                    'saved_amount' => $g['saved_amount'],
                    'target_date' => $asOf->copy()->addDays($g['days_from_as_of']),
                ]);
                $goal->id = $g['id'];

                return $goal;
            });

            // Goals are passed to the FINANCIAL snapshot but never reach the
            // scoring engine — the fixture records that separation.
            $snapshot = $engine->snapshot($profile, $goals, $asOf);

            $cases[] = [
                'name' => $case['name'],
                'note' => $case['note'],
                'input' => [
                    'profile' => $case['profile'],
                    'goals' => $case['goals'],
                ],
                'expected' => $scoring->score($snapshot)->toArray(),
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter scoring engine is '
                .'asserted against this file. Do not edit by hand.',
            'model_version' => FynnScoreEngine::MODEL_VERSION,
            'as_of' => ParityCases::AS_OF,
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('fynnscore_parity.json', $json);
    }

    private function writeMatchFixture(
        FinancialEngine $engine,
        FynnMatchEngine $matching,
    ): int {
        $asOf = Carbon::parse(ParityCases::AS_OF);
        $cases = [];

        foreach (MatchCases::all() as $case) {
            $snapshot = $engine->snapshot(
                new FinancialProfile($case['profile']),
                collect(),
                $asOf,
            );

            $request = new MatchRequest(
                amount: Money::of($case['request']['amount']),
                tenureMonths: $case['request']['tenure_months'],
                purpose: $case['request']['purpose'],
            );

            $matches = $matching->match($request, $snapshot, $case['age']);

            $cases[] = [
                'name' => $case['name'],
                'note' => $case['note'],
                'input' => [
                    'profile' => $case['profile'],
                    'age' => $case['age'],
                    'request' => $case['request'],
                ],
                'expected' => [
                    'matches' => array_map(
                        fn ($match) => $match->toArray(),
                        $matches,
                    ),
                    'match_count' => count(array_filter(
                        $matches,
                        fn ($m) => $m->category->isViable(),
                    )),
                    'evaluated_count' => count($matches),
                ],
            ];
        }

        $payload = [
            '_comment' => 'Generated by `php artisan fynn:parity-fixture`. '
                .'Laravel is authoritative; the Flutter matching engine is '
                .'asserted against this file. Do not edit by hand.',
            'as_of' => ParityCases::AS_OF,
            'affordability_ceiling_percent' => FynnMatchEngine::AFFORDABILITY_CEILING_PERCENT,
            'disclaimer' => FynnMatchEngine::DISCLAIMER,
            'cases' => $cases,
        ];

        $json = json_encode(
            $payload,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION,
        )."\n";

        return $this->put('fynnmatch_parity.json', $json);
    }

    private function put(string $filename, string $json): int
    {
        $targets = [
            base_path('tests/fixtures/'.$filename),
            // The Flutter project sits alongside this one; keeping a copy
            // there lets its suite run without reaching across repositories.
            base_path('../fynnedge/test/fixtures/'.$filename),
        ];

        foreach ($targets as $path) {
            $dir = dirname($path);
            if (! is_dir($dir)) {
                if (str_contains($path, '../fynnedge/')) {
                    $this->warn("Skipping {$path} — the Flutter project is not alongside this one.");

                    continue;
                }
                mkdir($dir, 0755, true);
            }

            if ($this->option('check')) {
                $existing = is_file($path) ? file_get_contents($path) : null;
                if ($existing !== $json) {
                    $this->error("Stale fixture: {$path}");

                    return self::FAILURE;
                }

                continue;
            }

            file_put_contents($path, $json);
            $this->info("Wrote {$path}");
        }

        return self::SUCCESS;
    }
}
